-- role_type følger katalogens kategori; politiske/offentlige verv og eksamen beholder sin undertype
CREATE OR REPLACE FUNCTION pg_temp._rtype(cat text, old text) RETURNS text LANGUAGE sql AS $f$
  SELECT CASE
    WHEN cat = 'position'  AND old IN ('political','public_office') THEN old
    WHEN cat = 'education' AND old IN ('education','exam') THEN old
    WHEN cat = 'other'     THEN 'other'
    ELSE cat END
$f$;

